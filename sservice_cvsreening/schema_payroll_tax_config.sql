-- ================================================================
-- DYNAMIC TAX & BPJS CONFIGURATION
-- Moves PPh21 TER brackets and BPJS employee-contribution rates out of
-- hardcoded Go constants into the database, so Finance/Admin can update
-- them from the UI whenever regulations change — no redeploy needed.
-- ================================================================

CREATE TABLE IF NOT EXISTS bpjs_rate_config (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1), -- singleton row
    kesehatan_rate_employee DECIMAL(6,4) NOT NULL DEFAULT 0.01,
    kesehatan_salary_cap DECIMAL(15,2) NOT NULL DEFAULT 12000000,
    jht_rate_employee DECIMAL(6,4) NOT NULL DEFAULT 0.02,
    jp_rate_employee DECIMAL(6,4) NOT NULL DEFAULT 0.01,
    jp_salary_cap DECIMAL(15,2) NOT NULL DEFAULT 10042300,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO bpjs_rate_config (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- PPh21 TER (Tarif Efektif Rata-rata, PMK 168/2023) brackets, per PTKP category (A/B/C).
-- up_to = NULL means "and above" (the last, unbounded bracket).
