    id SERIAL PRIMARY KEY,
    category CHAR(1) NOT NULL CHECK (category IN ('A', 'B', 'C')),
    bracket_order INTEGER NOT NULL,
    up_to DECIMAL(15,2), -- NULL = unbounded (highest bracket)
    rate DECIMAL(6,4) NOT NULL,
    UNIQUE(category, bracket_order)
);

CREATE INDEX IF NOT EXISTS idx_pph21_ter_brackets_category ON pph21_ter_brackets(category, bracket_order);

