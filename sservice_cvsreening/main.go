package main

import (
	"context"
	"log"
	"os"
	"time"

	"github.com/gin-gonic/gin"
	"github.com/joho/godotenv"
	_ "github.com/ryantriananda/sservice_cvsreening/docs" // Docs generated by Swag CLI
	"github.com/ryantriananda/sservice_cvsreening/repository"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"
)

// @title           CV models.Screening Service API
// @version         1.0
// @description     This is the backend service for the CV models.Screening application.
// @termsOfService  http://swagger.io/terms/

// @contact.name   API Support
// @contact.url    http://www.swagger.io/support
// @contact.email  support@swagger.io

// @license.name  Apache 2.0
// @license.url   http://www.apache.org/licenses/LICENSE-2.0.html

// @host      localhost:8081
// @BasePath  /api

// @securityDefinitions.apikey BearerAuth
// @in header
// @name Authorization

var aiService *AIService
var emailService *EmailService
var notificationEngine *NotificationEngine

func main() {
	// Load environment variables
	if err := godotenv.Load(); err != nil {
		log.Println("Warning: .env file not found, using environment variables")
	}

	apiKey := os.Getenv("OPENAI_API_KEY")
	if apiKey == "" {
		log.Fatal("OPENAI_API_KEY environment variable not set. Please create a .env file or set it in your environment.")
	}
	orgID := os.Getenv("OPENAI_ORG_ID")

	// Initialize Database
	if err := repository.InitDB(); err != nil {
		log.Printf("Warning: Failed to initialize database: %v", err)
		log.Println("Continuing without database - results will not be persisted")
	}

	if repository.IsDBConnected() {
		// Run Migrations
		if err := repository.RunMigrations(); err != nil {
			log.Fatalf("Failed to run migrations: %v", err)
		}

		// Run Seeders — data-driven list instead of one if-block per file, so adding a
		// new migration is a one-line append instead of a copy-pasted 3-line block.
		// Order matters (later schemas can reference earlier ones' tables), so this
		// stays a slice, not a directory scan.
		seedFiles := []string{
			"seed_psychotest.sql",
			"seed_questions.sql",
			"seed_questions_id.sql",
			"seed_users.sql",
			"migration_add_expected_answers.sql", // safe to re-run, uses UPDATE only
			"schema_extended_modules.sql",
			"schema_documents_extra.sql",
			"schema_office_settings.sql",
			"schema_attendance_location_exemptions.sql",
			"schema_attendance_correction.sql",
			"schema_approval_engine.sql",
			"schema_overtime_request.sql",
			"schema_payroll_grades.sql",
			"schema_payroll_tax_config.sql",
			"schema_payroll_deductions.sql",
			"schema_insurance.sql",
			"schema_allowances.sql",
			"schema_flexible_retirement.sql",
			"schema_insurance_continuation.sql",
			"schema_career_paths.sql",
			"schema_leadership_programs.sql",
			"schema_candidate_link.sql",
			"schema_candidate_location.sql",
			"schema_contract_approval.sql",
			"schema_overtime_approval.sql",
			"schema_shift_swap.sql",
			"schema_succession_risk.sql",
			"schema_claims.sql",
			"schema_claim_approval.sql",
			"schema_survey.sql",
			"seed_survey.sql",
		}
		for _, f := range seedFiles {
			if err := repository.RunSeed(f); err != nil {
				log.Printf("Failed to run seed/migration %s: %v", f, err)
			}
		}

		// Create test users for development/testing only — never in production,
		// where this would seed known-password admin/test accounts on a public server.
		if appEnv := os.Getenv("APP_ENV"); appEnv != "production" {
			if err := CreateTestUsers(context.Background()); err != nil {
				log.Printf("Warning: Failed to create test users: %v", err)
			}
		} else {
			log.Println("APP_ENV=production: skipping test user seeding")
		}

		// Apply database indexes for performance
		// if err := repository.ApplyDatabaseIndexes(context.Background()); err != nil {
		// 	log.Printf("Warning: Failed to apply database indexes: %v", err)
		// }

	}
	defer repository.CloseDB()

	// Initialize Cache
	InitCache()

	// Initialize Rate Limiter
	InitRateLimiter()

	// Initialize AI Service
	var err error
	aiService, err = NewAIService(apiKey, orgID)
	if err != nil {
		log.Fatalf("Failed to initialize AI service: %v", err)
	}
	defer aiService.Close()

	// Initialize Email Service
	emailService = NewEmailService()

	// Initialize Notification Engine
	notificationEngine = NewNotificationEngine()

	r := gin.Default()

	// Apply global middleware
	r.Use(CORSMiddleware())
	r.Use(RequestLogger())

	// Apply Global Rate Limiting (100 req/min) across all routes
	r.Use(RateLimitMiddleware(100, time.Minute))

	// Swagger Route
	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	api := r.Group("/api")
	registerPublicRoutes(r, api)

	// =====================================================
	// SYSTEM & SETTINGS ROUTES
	// NOTE: no routes are registered directly under a generic
	// "admin"-role group — admin-only endpoints below are scoped
	// individually with AdminOnly()/RoleMiddleware() as needed.
	//
	// Route registration is split by module into routes_*.go files (see
	// registerXxxRoutes below) — main() just wires them up in order. This is a
	// pure structural split: same routes, same order, same middleware, nothing
	// behavioral changed.
	protected := api.Group("/")
	protected.Use(AuthMiddleware())
	registerRecruitmentAdminRoutes(protected)
	registerAttendanceRoutes(protected)
	registerHRRoutes(protected)
	registerBenefitsSuccessionRoutes(protected)
	registerDocumentsOnboardingRoutes(protected)
	registerAdminFinanceRoutes(protected)
	registerSurveyRoutes(protected)

	r.GET("/health", func(c *gin.Context) {
		c.JSON(200, gin.H{
			"status":   "service up",
			"database": repository.IsDBConnected(),
		})
	})

	port := os.Getenv("PORT")
	if port == "" {
		port = "8081"
	}

	log.Printf("models.Screening Service running on :%s", port)
	if err := r.Run(":" + port); err != nil {
		log.Fatal("Failed to run service:", err)
	}
}
